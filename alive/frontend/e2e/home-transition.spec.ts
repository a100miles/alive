import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('alive-intro-seen', '1'))
})

test('dark listening band, sharp films and scroll-responsive frost', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.home-colophon')).toHaveCount(0)
  await expect(page.locator('.home-video-stage')).toHaveCSS('mask-image', 'none')
  await expect(page.locator('.scroll-frost')).toHaveCSS('opacity', '0')
  await page.evaluate(() => scrollTo(0, 90))
  await expect.poll(() => page.locator('.scroll-frost').evaluate(el => Number(getComputedStyle(el).opacity))).toBeCloseTo(.5, 1)
  await page.locator('.home-listening').scrollIntoViewIfNeeded()
  await expect(page.locator('.home-listening-band')).toHaveCSS('background-color', 'rgb(23, 23, 23)')
  await expect(page.locator('.home-listening-band')).toHaveCSS('color', 'rgb(248, 247, 243)')
  await expect(page.locator('.site-footer')).toHaveCSS('border-top-width', '0px')
  await expect(page.locator('.home-listening .underlined-link')).toHaveCSS('border-bottom-width', '0px')
  await expect(page.locator('.scroll-frost')).toHaveCSS('opacity', '1')
  await expect(page.locator('.scroll-frost')).toHaveCSS('pointer-events', 'none')
  await page.evaluate(() => scrollTo(0, 0))
  await expect(page.locator('.scroll-frost')).toHaveCSS('opacity', '0')
})

for (const width of [1440, 768, 390]) {
  test(`shared disc flight and history ${width}`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width, height: 900 })
    await page.clock.install()
    await page.goto('/')
    const link = page.locator('.home-release')
    await link.scrollIntoViewIfNeeded()
    await expect(page.locator('.home-listening')).toHaveCSS('opacity', '1')
    await page.screenshot({ path: `../../.impeccable/dark-listening/home-${width}.png` })
    await page.clock.pauseAt(await page.evaluate(() => Date.now() + 100))
    await link.focus()
    await link.press('Enter')
    await expect(page.locator('.disc-flight')).toHaveCount(1)
    await page.clock.runFor(150)
    expect(new URL(page.url()).pathname).toBe('/')
    await link.dispatchEvent('click')
    await expect(page.locator('.disc-flight')).toHaveCount(1)
    await page.clock.runFor(200)
    expect(new URL(page.url()).pathname).toBe('/music')
    await page.clock.runFor(430)
    await page.screenshot({ path: `../../.impeccable/dark-listening/flight-${width}.png` })
    await page.clock.runFor(380)
    const flight = await page.locator('.disc-flight-plane').boundingBox()
    const destination = await page.locator('.scene-incoming .archive-disc.is-active').boundingBox()
    expect(flight).not.toBeNull(); expect(destination).not.toBeNull()
    for (const key of ['x', 'y', 'width', 'height'] as const) expect(Math.abs(flight![key] - destination![key]), JSON.stringify({ key, flight, destination })).toBeLessThan(2)
    await page.clock.runFor(300)
    await expect(page.locator('.disc-flight')).toHaveCount(0)
    await expect(page.locator('.archive-disc.is-active')).toHaveCSS('visibility', 'visible')
    await expect(page.locator('h1')).toBeFocused()
    await page.clock.resume()
    await page.goBack()
    await expect(page.locator('.home-listening-band')).toBeVisible()
    await expect(page.locator('.home-disc')).toHaveCSS('visibility', 'visible')
    await page.goForward()
    await expect(page.locator('.music-scene')).toBeVisible()
    await expect(page.locator('.disc-flight')).toHaveCount(0)
    expect(errors).toEqual([])
  })
}

test('reduced motion interrupts flight and direct Music navigation still works', async ({ page }) => {
  await page.goto('/')
  await page.locator('.home-release').scrollIntoViewIfNeeded()
  await page.clock.install(); await page.clock.pauseAt(await page.evaluate(() => Date.now() + 100))
  await page.locator('.home-release').click({ force: true })
  await page.clock.runFor(100)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('.disc-flight')).toHaveCount(0)
  await expect(page.locator('.music-scene')).toBeVisible()
  await expect(page.locator('h1')).toBeFocused()
  await page.clock.resume()
  await page.goBack()
  await page.locator('.home-release').click()
  await expect(page.locator('.disc-flight')).toHaveCount(0)
  await expect(page.locator('.music-scene')).toBeVisible()
  await page.reload()
  await expect(page.locator('.music-scene')).toBeVisible()
})

test('browser Back during arrival cancels the flight and restores Home interaction', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.locator('.home-release').scrollIntoViewIfNeeded()
  await page.clock.pauseAt(await page.evaluate(() => Date.now() + 100))
  await page.locator('.home-release').click({ force: true })
  await page.clock.runFor(400)
  expect(new URL(page.url()).pathname).toBe('/music')
  await page.goBack()
  await page.clock.runFor(1200)
  await expect(page.locator('.disc-flight')).toHaveCount(0)
  await expect(page.locator('#main-content')).not.toHaveAttribute('inert')
  await expect(page.locator('.home-disc')).toHaveCSS('visibility', 'visible')
})

test.describe('touch', () => {
  test.use({ hasTouch: true, viewport: { width: 390, height: 844 } })
  test('a tap completes the disc navigation', async ({ page }) => {
    await page.goto('/')
    await page.locator('.home-release').tap()
    await expect(page.locator('.music-scene')).toBeVisible()
    await expect(page.locator('.disc-flight')).toHaveCount(0)
    await expect(page.locator('h1')).toBeFocused()
  })
})

