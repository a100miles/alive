test('mobile layout, menu and synthesized touch gestures', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const page = await context.newPage()
  await page.addInitScript(() => sessionStorage.setItem('alive-intro-seen', '1'))
  for (const route of ['/', '/photography', '/music', '/about', '/contact']) {
    await page.goto(route)
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    await page.evaluate(() => document.fonts.ready)
    await page.waitForTimeout(850)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: path.join(review, route === '/' ? 'mobile.png' : `${route.slice(1)}-mobile.png`), fullPage: true })
  }
  await page.getByRole('button', { name: 'Open menu' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link', { name: 'Music', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Sound, held.')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  const session = await context.newCDPSession(page)
  await page.waitForTimeout(700)
  const stage = await page.locator('main .disc-stage').boundingBox()
  if (!stage) throw new Error('Disc stage missing')
  const y = stage.y + stage.height / 2
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 320, y }] })
  for (let x = 300; x >= 80; x -= 20) await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(page.locator('main .release-introduction h2')).not.toHaveText('Soft focus')
  await page.goto('/photography')
  await page.getByRole('button', { name: 'Horizontal view' }).click()
  await expect(page.locator('.photo-rail')).toBeVisible()
  await page.waitForTimeout(700)
  const rail = await page.locator('.photo-rail').boundingBox()
  if (!rail) throw new Error('Photo rail missing')
  const photoY = rail.y + rail.height / 2
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 320, y: photoY }] })
  for (let x = 300; x >= 60; x -= 20) await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: photoY }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect.poll(() => page.locator('.photo-rail').evaluate(element => element.scrollLeft)).toBeGreaterThan(100)
  await context.close()
})

