  const cdp=await context.newCDPSession(page),x=bounds.x+bounds.width/2,start=bounds.y+bounds.height*.7
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y:start}]})
  for(let y=start-20;y>start-200;y-=20){await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x,y}]});await page.waitForTimeout(20)}
