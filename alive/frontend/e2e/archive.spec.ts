test('interrupted intro cannot reopen after reduced motion is toggled back off',async({page})=>{
  await page.addInitScript(()=>sessionStorage.removeItem('alive-intro-seen'))
  await page.clock.install();await page.goto('/');await expect(page.getByRole('dialog',{name:'Introducing a.l.i.v.e'})).toBeVisible()
  await page.clock.pauseAt(Date.now()+50)
  await page.getByRole('button',{name:'Skip intro'}).click({force:true})
  await page.emulateMedia({reducedMotion:'reduce'});await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.emulateMedia({reducedMotion:'no-preference'});await page.clock.runFor(4000)
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.getByRole('heading',{level:1})).toHaveText('a.l.i.v.e')
  await page.clock.resume()
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Contact',exact:true}).click()
  await expect(page.getByRole('heading',{level:1})).toHaveText('Let’s keepin touch.')
})

