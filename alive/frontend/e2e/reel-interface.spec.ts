import { test, expect } from '@playwright/test'

test('reel protects transparent filters across layouts and both browsing directions', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('alive-intro-seen', '1'))
  await page.goto('/photography')
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    const filters = page.locator('.reel-filters')
    const buttons = filters.locator('[data-album]')
    await expect(buttons.first()).toBeVisible()
    await page.evaluate(() => document.fonts.ready)
    await expect.poll(() => page.locator('.photo-reel').evaluate(root => {
      const toolbar = root.querySelector('.reel-toolbar')!.getBoundingClientRect()
      const protectedBottom = parseFloat(getComputedStyle(root).getPropertyValue('--reel-protected-bottom'))
      return protectedBottom - (toolbar.bottom - root.getBoundingClientRect().top)
    })).toBeGreaterThanOrEqual(0)
    for (const button of await buttons.all()) {
      await expect(button).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
      await button.hover()
      await expect(button).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
      await button.focus()
      await expect(button).toHaveCSS('outline-style', 'solid')
      await page.mouse.down()
      await expect(button).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
      await page.mouse.move(0, 0)
      await page.mouse.up()
    }
    await buttons.nth(1).click()
    await expect(buttons.nth(1)).toHaveAttribute('aria-pressed', 'true')
    await expect(buttons.nth(1)).toHaveCSS('border-bottom-color', 'rgb(23, 23, 23)')
    await buttons.first().click()
    const stage = page.locator('.reel-stage')
    await stage.focus()
    const initial = await page.locator('.reel-plane.is-active').getAttribute('aria-label')
    await page.keyboard.press('ArrowDown')
    await page.waitForTimeout(400)
    await page.screenshot({ path: `../../.impeccable/reel-interface/down-${width}.png` })
    await page.keyboard.press('ArrowUp')
    await page.waitForTimeout(400)
    await page.screenshot({ path: `../../.impeccable/reel-interface/up-${width}.png` })
    await page.waitForTimeout(1200)
    await expect(page.locator('.reel-plane.is-active')).toHaveAttribute('aria-label', initial!)
    await page.screenshot({ path: `../../.impeccable/reel-interface/rest-${width}.png` })
    await page.keyboard.press('Enter')
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(stage).toBeFocused()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.locator('.reel-stage').focus()
  await page.locator('.reel-plane.is-active').hover()
  await page.mouse.wheel(0, 450)
  await expect(page.locator('.reel-readout strong')).toHaveText('03')
  await page.waitForTimeout(1200)
  await page.mouse.wheel(0, -450)
  await expect(page.locator('.reel-readout strong')).toHaveText('01')
  await page.waitForTimeout(1200)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('.reel-dissolve').first()).toHaveCSS('backdrop-filter', 'none')
  await page.locator('.reel-stage').focus()
  await page.keyboard.press('ArrowDown')
  await expect(page.locator('.reel-readout strong')).toHaveText('02')
  await page.getByRole('button', { name: 'Horizontal view' }).click()
  await expect(page.getByRole('button', { name: 'Perspective reel' })).toBeFocused()
})
